export const POET_NAMES = POETS.map((p) => p.name);

export function getPoet(name) {
  return POETS.find((p) => p.name === name) || null;
}

/** 给模型看的风格提要 */
export function poetBrief(name) {
  const p = getPoet(name);
  if (!p) return '';
  return `【要以${p.name}的笔法写（${p.era}）】
  其人：${p.life}
  其笔法：${p.style}
  落笔要点：${p.guide}
  他常用的物象：${p.imagery}
  最容易学坏的地方：${p.avoid}
  【铁律】只许学他的笔法与取景方式，**绝不可套用、改写或拼接他的任何成句**。
    任何一句读来让人想到他的某句名作，即为失败。要写的是眼前这个场景，用他的眼睛看而已。`;
}
