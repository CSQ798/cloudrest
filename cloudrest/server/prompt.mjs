/* ============================================================
 * 三、格律：把已核验的谱面直接给模型，并要求逐字遵守
 * ============================================================ */
function tuneBrief(name) {
  const tune = getTune(name);
  if (!tune) return '';
  const parts = [];
  const skeleton = [];
  let idx = 0;
  for (const n of tune.stanzas) {
    const rows = [];
    for (let k = 0; k < n; k++, idx++) {
      rows.push(
        `    第 ${idx + 1} 句 ${tune.lens[idx]} 字，平仄 ${tune.tones[idx]}${tune.rhymes[idx] ? '（押韵）' : ''}`
      );
      skeleton.push('　'.repeat(Math.max(0, 8 - tune.lens[idx])) + '○'.repeat(tune.lens[idx]) + (tune.rhymes[idx] ? '◆' : ''));
    }
    parts.push(`  ${tune.stanzas.length > 1 ? (parts.length === 0 ? '上片' : '下片') : '全篇'}：\n${rows.join('\n')}`);
  }
  const notes = getTuneNotes(name);
  return `【《${name}》格律（据《钦定词谱》${tune.author}词，共 ${tune.total} 字）】
  ${tune.desc}
${parts.join('\n')}
${notes ? `\n  体式要点（合谱还不够，这些才见出这个调子的样子）：\n  ${notes}\n` : ''}
  句式骨架（○ 代表一个字；行末有 ◆ 的必须押韵。必须写成 ${tune.lens.length} 句，每句字数与下列完全一致。骨架里的 ○ 与 ◆ 只是记号，正文里一个字都不要写）：
${skeleton.join('\n')}`;
}

function shiBrief(name) {
  const pats = shiPatterns(name);
  if (!pats) return '';
  const size = name.startsWith('五') ? 5 : 7;
  const lines = pats
    .map((p, i) => `    式${i + 1}：${p.lines.join(' / ')}　（韵脚句：${p.rhyme.map((x, k) => (x ? k + 1 : '')).filter(Boolean).join(',')}）`)
    .join('\n');
  const para = parallelCouplets(name);
  return `【《${name}》格律】
  每句 ${size} 字，共 ${pats[0].lines.length} 句。四种正格（任选其一，全篇照一式到底）：
${lines}

  句式骨架（○ 代表一个字，共 ${pats[0].lines.length} 句，每句 ${size} 字，一句一行）：
${pats[0].lines.map(() => '　'.repeat(0) + '○'.repeat(size)).join('\n')}

  说明：平仄须逐字遵守。偶句必押平声韵，且须同属平水韵一个韵目（首句可入韵可不入韵，见各式韵脚句）。
${para.length ? `  中间两联（第 ${para.map((c) => c + 1).join('、')} 联）必须对仗：词性相对、结构相称、意义相承。` : '  绝句不要求对仗，但若有对句更佳。'}`;
}

export function patternBrief(form) {
  if (getTune(form)) return tuneBrief(form);
  if (SHI_NAMES.includes(form)) return shiBrief(form);
  return '';
}

/**
 * 未核验体裁（用户自填的词牌）：我没有它的词谱，不能替它编格律。
 * 改为要求模型先声明所用句式，再照自己声明的句式写；
 * 服务端随后机械核对「正文是否与自述句式一致」，并把「未核验」如实告诉用户。
 */
export function declaredBrief(form) {
  return `【《${form}》的格律（我手里没有这个词牌已核验的词谱）】
  请你自己据所知的《${form}》词调，先在 <meter> 里声明它的句式：每句字数用 / 隔开；
  分片的词牌，片与片之间用「 | 」隔开（如《水调歌头》上片 5/5/6/5/6/6/5/5/5 | 下片 3/3/3/4/7/6/6/5/5/5）。
  然后严格照这个句式写正文，正文的句数、每句字数、分片都要与你声明的完全一致。
  若你不确定《${form}》的句式，宁可选一个你确知的常见词牌重报，不可乱写。`;
}

