export function composePrompt(form, scene, wish, feedback, previous, poet, allusionIds) {
  const brief = isVerifiedForm(form) ? patternBrief(form) : declaredBrief(form);
  const parts = [];
  // 风格放在最前：先立定「用谁的眼睛看」，再定格律，再给场景
  if (poet && getPoet(poet)) parts.push(poetBrief(poet));
  parts.push(`【本次要写的体裁与格律】\n${brief}`);
  parts.push(`【场景】\n${scene.trim()}`);
  const ab = allusionBrief(scene, 8, allusionIds);
  if (ab) parts.push(ab);
  if (wish && wish.trim()) parts.push(`【用户的额外要求】\n${wish.trim()}`);
  if (previous && previous.body) {
    // 两种毛病要两种改法：
    //   句式/字数/押韵错了 —— 多半是整句没排好，重写全篇反而更容易对；
    //   只剩平仄几处不合 —— 重写全篇会把已经对的地方又改坏，实测越改越差。
    // 所以后者改成「外科手术」：只换点到的那几个字，其余一字不动。
    const mustRewrite = /【必改】/.test(feedback);
    parts.push(
      `【上一稿】\n${previous.body.trim()}\n\n【上一稿的问题（逐条改掉）】\n${feedback}\n\n` +
        (mustRewrite
          ? '请照这些问题重写全篇。不要逐字修补，宁可整句换掉；先把每个字的平仄与韵脚排好，再定字面。'
          : '句数、字数、押韵都已经合了，**不要重写全篇**。只把上面点到的那几个字逐个换掉，' +
            '其余的字一个都不要动；换完仍须读得通、仍是同一首诗、要说的事一点不变。' +
            '拿不准的位置，「中」处可平可仄，不必管它。')
    );
  }
  parts.push(
    '现在写这一首。落笔前请逐句核对：句数是否等于骨架行数、每句字数是否等于该行 ○ 的个数、' +
      (isVerifiedForm(form) ? '每个字的平仄是否与该行所标一致（「中」处随意）、' : '') +
      '行末有 ◆ 的是否押了同一个韵部。宁可慢，不可失律。'
  );
  return parts.join('\n\n');
}

