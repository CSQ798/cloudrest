export function refinePrompt(form, scene, wish, previous, feedback, poet, allusionIds) {
  const brief = isVerifiedForm(form) ? patternBrief(form) : declaredBrief(form);
  const parts = [];
  if (poet && getPoet(poet)) parts.push(poetBrief(poet));
  parts.push(`【场景】\n${scene.trim()}`);
  parts.push(`【体裁】《${form}》，格律不可改：\n${brief}`);
  const ab = allusionBrief(scene, 6, allusionIds);
  if (ab) parts.push(ab);
  parts.push(`【用户的新要求】\n${wish.trim()}`);
  parts.push(`【上一稿】\n${previous.body.trim()}`);
  if (previous.scene) parts.push(`【上一稿的取景】${previous.scene}`);
  if (previous.meter) parts.push(`【上一稿声明的句式】${previous.meter}`);
  if (feedback) parts.push(`【上一稿的格律问题】\n${feedback}`);
  parts.push('照用户的新要求改这一首。句式是底线：改完仍须与上面给的句式逐句一致' + (isVerifiedForm(form) ? '，且逐字合平仄、韵脚同韵' : '') + '。');
  return parts.join('\n\n');
}
