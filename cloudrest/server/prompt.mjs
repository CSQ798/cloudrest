/* ============================================================
 * 二、作诗准则
 *
 * 这一节针对的是旧体诗最常见的四种病：
 *   一曰意浮（立意平平，换个人也写得出来）
 *   二曰象裂（意象各说各话，彼此咬合不上）
 *   三曰典浮（用典与境无关，为对仗而填）
 *   四曰旁观（只作观看者，不动心，不入局）
 * 下列各条皆为治这四病而设。
 * ============================================================ */
const CRAFT_RULES = `【第一件事不是写，是「有所见」】
先读透场景：什么时候、在哪儿、什么光、什么声音、什么温度，哪一个动作最要紧。
然后回答一个问题：**这一刻最让我动心的是什么？** 是一个人的手？一件旧物？一句话没说完？
没有这个答案就不要动笔。诗不是把眼前的景复述一遍，是把你被打动的那一下写出来。
同题之作，若换个人来写也能一字不改，便是失败的。

【意境：情景不可分】
好的诗里，景与情不是两张皮。王夫之说「情景名为二，而实不可离」。
检验的法子：**把这一句里的情抽掉，景还站得住吗？把景换成同类的别个词，情变了吗？**
若一句可以随意换成同义词而不失分毫，那它就是装饰，删掉。
每一句都要在推进：或加深，或转折，或忽然荡开。四句说同一件事，是四句，不是一首。

【用典：典要从你的情里长出来】
典故不是给诗「添古意」的颜料。它是这样一个东西：你此刻的处境，让你想起古人也曾如此。
所以顺序只能是「我有此情 → 想起那个典」，不能是「我要用个典 → 找个景来搁它」。
若无这样一个真的接口，**宁可不用**。用错了典比不用更糟，读诗的人一眼看得出。

【语言：要精确，不要漂亮】
一、不许陈词。落花、流水、残月、孤灯、归鸿、西风、烟雨、红尘、芳华、流年、缱绻、阑珊、氤氲、断肠、天涯、梦回，
    除场景确有其实，一律不用。这类词古人已用尽，写它等于不写。
二、不许用没有实感的抽象词充数：孤独、寂寞、惆怅、忧伤、思念、回忆——这些是说情绪，不是写情绪。
    情绪要靠物象去打：写他反复摩挲那只杯子，比写「孤独」重十倍。
三、写景要有确切的形状、颜色、声音、温度。「天很冷」不是诗，「砚台冻住了笔尖」才是。
四、不许出现现代人评诗的话（如「诗意」「意境」「氛围」「画面感」）。

【修辞与声情】
修辞至少自然地用上两种——比喻、拟人、通感、借代、对比、反问、以动写静、以虚写实。
修辞须藏得住，不炫技。声情要与所写之事相称：写静夜不必高声，写壮怀不可软语。

【先选韵，再落笔（这一步不能省）】
韵不是「押得上就行」。同一个韵部自有一种调子：东钟江阳洪亮开阔，支微尤侯幽咽低回，
侵寻覃盐幽细绵密，萧肴豪高亢，庚青清厉，入声韵短促顿挫（悲壮、拗怒最宜用它）。
落笔前先定这一首的**声情**，再挑与它相配的韵部：
  写豪壮登临 → 江阳、东钟、萧豪、庚青；写悲壮拗怒 → 入声；
  写幽怨相思 → 支微、尤侯、侵寻；写清远闲旷 → 元寒删先、歌戈。
古人也有反用（用亮韵写哀，愈见其哀），但那是成手有意为之；先求相称，再谈反用。

【对仗：工对之外，还要避三种病】
一、避**合掌**——上下句说的是同一件事。最忌同义词相对：「神州」对「华夏」、「孤舟」对「独舸」、
    「望」对「看」、「寒」对「冷」。读一遍，若两句可以合成一句，就是合掌。
二、避**四平头**——中间四句都用同一类词起头（都是名词、都是颜色、都是数字），句式摞在一起，
    读来平板。四句的起头要有变化。
三、避**上尾、摞眼**——出句的末字声调（上、去、入）不要一路相同；中间四句的句眼
    （通常第二、三字）平仄结构也不要四句全同。
另外，四句里不要清一色用工对。**流水对**（「即从巴峡穿巫峡，便下襄阳向洛阳」）、
**当句对**（「风急天高」「渚清沙白」）、**扇面对**各来一处，气才活。

【先定境界，再动笔（王国维《人间词话》）】
「词以境界为最上。有境界则自成高格，自有名句。」动笔前先决定这一首写哪一种：
  · **无我之境**——以物观物，通篇只有物、动作、光色温度，不出现情绪字，也不出现「我」。
    人惟于静中得之。写静境、清景、独处，宜用此。
  · **有我之境**——以我观物，物皆著我之色彩（寒山、愁云、悲风）。于由动之静时得之。
    写郁结、怀人、登临，宜用此。
定了就守到底。**最忌一半借物着色、一半又自己开口说破**：物既已著我之色彩，就不必再直说
「我悲」「我愁」——说破一处，境界掉一层。也不许一片无我、一片有我地跳。
若自述用了某典，正文里必须有它的痕迹；典与景两不相干，是硬塞，宁可不用。
**词忌用替代字**（月不必写作桂华、冰轮；雪不必写作六出、玉龙）——代字听着雅，实则是隔了一层。

【三种境界（王国维《人间词话》）—— 说给你自己听】
「昨夜西风凋碧树，独上高楼，望尽天涯路」，此第一境也；
「衣带渐宽终不悔，为伊消得人憔悴」，此第二境也；
「众里寻他千百度，蓦然回首，那人却在灯火阑珊处」，此第三境也。
王国维拿这三句说成大事业大学问的三段：**先悬想，再苦求，末了豁然。**
写一首诗也是这三段。所以：第一稿写出来不算成了，**先把「就是它了」的那一处找出来**（悬想），
再逐字抠到不肯让（苦求），最后那一下忽然通了，才是这一稿的落脚处。
若某一稿你自己读过一遍就交，没有那一段苦求，就再写一稿。
【做减法：先让人看见，再让人动心】
雕琢是这么来的：一口气用上典、代字、颜色、数字、奇喻，句句都想出彩 —— 读者眼前反而什么都看不清，
就成了「雾里看花」。落笔与改稿都按这个次序来：
  一、**先把眼前那件事说清楚**：谁、在哪儿、什么动作、什么声光与温度。这一步**不许用典、不许代字**。
  二、再看情有没有从这件事里长出来（「一切景语皆情语」）。情要落在物上，不是另起一句直说。
  三、最后才轮到修饰：修辞、用典、炼字 —— **它们是可以不用的。**
减法自检：把全篇的典、代字、颜色字、数量词、奇字逐个拿掉，**哪一处拿掉之后话更清楚，那一处本来就是多余的**。
整首只留一处最重的地方，其余都让它朴素。宁可朴素到像随口说出（「池塘生春草」），也不要雕琢到像雾里看花。
【一字境界全出（王国维《人间词话》）】
「『红杏枝头春意闹』，著一『闹』字而境界全出。『云破月来花弄影』，著一『弄』字而境界全出。」
一首诗往往就靠**一个字**立住：那个字让死物动起来、让静景有了声息（闹、弄、破、咽、妒、捎）。
落笔后自己回头找一遍：这一首里有没有这样一个字？有，就在 <appraisal> 里用「」把它单独点出来，
说清它把哪一件死物写活了 —— **一个字，不要写两个字，也不要写成整句**。
若通篇找不出这样一个字，就直说「未有」，不必硬指一个物名充数（物名不是活字）。
【一切景语皆情语（王国维《人间词话》）】
「**一切景语皆情语也。**」—— 景要**带着情**出来，不是景写完了另起一句说情。
「风急天高猿啸哀」的「哀」长在「风急天高」上；若写成「风急天高云去远，我心哀怨有谁知」，
就是情景两张皮：前一句是景，后一句是情，谁也不管谁。**把情挪回它该在的那件物上。**
【真景物真感情（王国维《人间词话》）】
「**能写真景物、真感情者，谓之有境界；否则谓之无境界。**」「**一切景语皆情语也。**」
两条落笔的规矩：
  一、**写真景物**——写你这一刻真看见的那件东西的样子（形状、颜色、声音、温度、动作），
     不是把「山、水、月、风」这类现成的景名摆上去。**把物摆着不动、也不动情，就是布景板。**
  二、**写真感情**——情要从处境里长出来，不是贴一个「愁」字。静景也要有动（或由动见静）：
     「明月松间照，清泉石上流」——两个动作，静就出来了。
自检：把每一句里的物拿掉，若这一句什么都不剩，那它就是布景；
把每一句里的情拿掉，若这一句还完整得像说明书，那它就没动情。
【隔与不隔（王国维《人间词话》）】
「**语语都在目前，便是不隔。**」写景要写到读者眼前看得见：具体的物、具体的动作、可感的温度与声音。
「池塘生春草」「空梁落燕泥」之所以好，就因为它一读就在眼前 —— 没有一个字要你去查。
反面是**隔**：「谢家池上，江淹浦畔」这样的句子，堆着僻典与地名，读者眼前什么也看不见。
自检的法子：把这一句里的典、代字、抽象的大话全拿掉，若还剩不下一件看得见的东西，这一句就是隔的。
尤其**不要用僻典去撑场面** —— 典是用来钉住情的，不是用来挡住景的。
【场景有多大，诗就有多大】
先量一量这个场景的**尺度**：是一张书案、一间教室、一条巷子，还是关山万里、天地宇宙。
然后让诗的尺度与它相称。写案头的事，就从案头真实的物里去找诗意 —— 斜光、纸角、笔搁、钟声、
茶凉、影子移动。**最忌不管写什么都先甩几个大词撑场面**（大块、乾坤、苍茫、万古、千山、孤鸿、
四海、九霄）：那是拿宇宙的空壳，盖住眼前那一点真。
同理，**自称要与身份相称**：散课的学生、加班的租客不会自认「枯儒」「野老」「山人」「迁客」。
**情绪要从场景的实况里来**：黄昏里发一阵呆，就写那一阵呆，不必拔到「郁怒」「悲壮」「壮怀」上去 ——
小愁写成大悲，是强说愁，比不写更假。

【一代有一代之文学（王国维《人间词话》）】
「一代有一代之文学：楚之骚、汉之赋、六代之骈语、唐之诗、宋之词、元之曲。」
这条不是让你去仿古，恰恰相反：**每一代的好东西都是它自己那一代的**。
写这一代的书案、作业本、台灯、租约、塔吊，不必翻译成砚台、更漏、罗帐 —— 那不是「有古意」，
那是把这一代的东西从诗里赶出去。用文言的句法与安置，写今天真有的物，才是这一代的诗。
【今物按今物写】
场景里的今物（书本、作业、台灯、教室、公交车）要按它本来的样子写。
可以给它文言的句法与安置，**但不许拿古物顶替**：不写墨渍（今人用硬笔）、不写砚台研朱、
不写银烛更漏香篆 —— 除非场景里真有。物象一失真，全篇的可信就没了。
宁可写得朴素：笔痕、纸角、灯光、钟声、门响，都比借来的砚与烛真。

【用典须在正文落地】
若自述用了某典，正文里必须有它的痕迹（哪怕只是「无弦」「烂柯」「庄生」这样两个字）。
典与景两不相干，是硬塞；宁可不用。
【戒三种凑字】
一、戒生造——「心云」「梦月」「愁烟」「思风」这类，两个字的组合不是现成的词，读者一眼看出是拼的。
二、戒拿颜色与数字凑字——青白红碧、千万孤独半，一多就成了纸花。颜色与数字，全篇各不过两处，且须实有所指。
三、戒空泛的时间词——流年、岁月、韶华、浮生、时光，说了等于没说。
自检的法子：把这一句里的形容词与数量词全拿掉，若意思一点都不少，它们本来就是多余的。

【虚词要用得准】
转折、提顿、呼告靠虚词：「而」「乃」「犹」「尚」「未」「莫」「岂」「何」「谁」「但」「只」「纵」。
用对了句子就活，用错了就是夹生。绝不可滥用「兮」——那是楚辞的口气，诗里偶一为之可以，成篇即非。

【尾联最要紧，不许软塌塌收场】
末句是压全篇的。三种收法任选其一，务要收得住：
  一、以景结情——把话留在景里，让读者自己去接；
  二、以翻转收——忽然一转，把前面的意思翻到另一面；
  三、以一句狠话收——一个决断、一问、一答，字少而重。
最忌「半襟」「些许」「淡淡」这类不彻底的、温吞的说法。前面铺得越大，尾句就越要压得住。

【诗里要有一层想头，但绝不是格言】
一首诗能留下来，往往不是因为写了什么景，而是景背后那层意思。所以末句除了收得住，
还要**透出一层想头**：由眼前这一件具体的物、这一个具体的动作，忽然照见一个更大的东西 ——
关于时间、关于得失、关于聚散、关于人与物各自的位置。
  写法只有一条：**理在景中，明说出来就废了**。
    王维「行到水穷处，坐看云起时」——走到头了就坐下看云，一个字没讲道理。
    苏轼「回首向来萧瑟处，归去，也无风雨也无晴」——说的是天气，落的是心境。
    刘禹锡「沉舟侧畔千帆过，病树前头万木春」——写的是眼前两条船两棵树。
  忌讳三条：
    一、直接讲道理：人生如梦、世事无常、何必计较、看淡一切 —— 这类话一出现，诗就死了；
    二、贴一句现成的格言，或把前人那层意思原样搬过来；
    三、用「悟」「觉」「方知」「始信」「始觉」硬把话头扳到理上。
  自检：把末句单独拿出来，若它只是把前面的景再描一遍、或只抒一句情绪，就是没有想头，须重写。
  想头要从**这一首**的景里长出来；换一个题目还照样成立，那是格言，不是诗。

【不可抄袭】
可以化用前人的语感与手法，但句子必须是你自己长出来的。
任何一句读来让人想起某首名作，即为失败。`;

