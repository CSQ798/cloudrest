let bad = 0;
for (const [name, wants, note] of EXPECT) {
  const t = getTune(name);
  if (!t) {
    console.log(`✗ ${name} 未在表中`);
    bad++;
    continue;
  }
  const ok = wants.includes(t.total);
  if (!ok) bad++;
  console.log(
    `${ok ? '✓' : '✗'} ${name.padEnd(5, '　')} 表中 ${String(t.total).padStart(3)} 字　` +
      `通行 ${wants.join('或')} 字（${note}）`
  );
}
console.log(`\n${EXPECT.length - bad}/${EXPECT.length} 与通行正体相符`);
console.log('\n表中全部词牌字数：');
for (const t of TUNES) console.log(`  ${t.name.padEnd(5, '　')} ${String(t.total).padStart(3)} 字　${t.desc}`);
process.exit(bad === 0 ? 0 : 1);
