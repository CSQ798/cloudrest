let pass = 0;
const failures = [];

function ok(name, cond, why, got) {
  if (cond) { pass++; console.log(`  ✓ ${name}`); }
  else { failures.push(name); console.log(`  ✗ ${name}\n      → 实得：${JSON.stringify(got)}\n      依据：${why}`); }
}
function eq(name, got, want, why) {
  ok(name + `  = ${JSON.stringify(want)}`, got === want, why, got);
}
function section(t) { console.log(`\n=== ${t} ===`); }

// 方便：把 why 也打印出来，让每条断言的依据可见
function okT(name, cond, why, got) {
  ok(name, cond, why, got);
  if (cond) console.log(`      依据：${why}`);
}
function eqT(name, got, want, why) { okT(name + `  = ${JSON.stringify(want)}`, got === want, why, got); }

// 「未收录字」样本：从扩展 B 区里挑一个确实不在韵书中的字，避免硬编码
const UNKNOWN = (() => {
  for (let cp = 0x20000; cp < 0x2a6e0; cp++) {
    const c = String.fromCodePoint(cp);
    if (toneOf(c) === '未知' && buOf(c).length === 0) return c;
  }
  return null;
})();

