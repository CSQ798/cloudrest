eqT('YUNMU 长度', YUNMU.length, 106, '《平水韵》共 106 韵目。');
eqT('YUNMU 声调分布', [30, 29, 30, 17].join('/'),
  [YUNMU.filter((y) => y.声 === '平').length, YUNMU.filter((y) => y.声 === '上').length,
   YUNMU.filter((y) => y.声 === '去').length, YUNMU.filter((y) => y.声 === '入').length].join('/'),
  '平 30（上平 15 + 下平 15）、上 29、去 30、入 17，合计 106。');
okT('YUNMU 每项都有 名 / 声 / 字:Set',
  YUNMU.every((y) => typeof y.名 === 'string' && ['平', '上', '去', '入'].includes(y.声) && y.字 instanceof Set && y.字.size > 0),
  '接口约定：{ 名, 声, 字: Set }。');
okT('「上声三讲」存在且非空（旧单源数据的缺口）',
  YUNMU.some((y) => y.名 === '上声三讲' && y.字.size > 0),
  '维基文库《平水韻》整条缺「上声三讲」；搜韵《平水韵》有（讲港棒蚌项耩）。');
eqT('BU 长度', BU.length, 19, '《词林正韵》共十九部。');
okT('BU 每项有 id/平/仄/上/去/入，且 仄 ⊇ 上∪去∪入',
  BU.every((b) => typeof b.id === 'string' && /^第.+部$/.test(b.id)
    && b.平 instanceof Set && b.仄 instanceof Set && b.上 instanceof Set && b.去 instanceof Set && b.入 instanceof Set
    && [...b.上, ...b.去, ...b.入].every((c) => b.仄.has(c))),
  '接口约定；「仄」为上、去、入之并集。');
eqT('pingOf(7) 含「天」', pingOf(7).has('天'), true, '第七部平声含一先，而「天」属一先。');
eqT('pingOf(越界) 返回空 Set', pingOf(99).size, 0, '越界不抛异常，返回空集合。');
eqT('buOf(未收录字) 返回空数组', buOf(UNKNOWN).length, 0, '未收录不猜测。');
eqT('pingBu(月) 返回 null（无平声部）', pingBu('月'), null, '入声字无平声归属。');
eqT('zeBu(月) 是数组', Array.isArray(zeBu('月')), true, '入声字有仄声归属，按数组返回。');

