  '《词林正韵》把《平水韵》上平十灰劈成两半：'
  + '「灰」半（灰恢魁隈回徊梅…杯…）入第三部；「咍」半（开哀埃台苔…来…）入第五部。'
  + '故 杯/回/徊 = 第三部，台/来 = 第五部。'
  + '此结论有四家独立记载一致：(a) 诗词家园《词林正韵》第三部【十灰(半)】列 杯回徊、'
  + '第五部【十灰(半)】列 台来；(b) GitHub charlesix59 Cilin_Rhyme.json 同此；'
  + '(c) cnkgraph 韵典「词林正韵/平声/四支五微八齐十灰(半)/杯」与「…/九佳(半)十灰(半)/台」；'
  + '(d) 搜狐《一曲新词酒一杯 去年天气旧亭台 晏殊的浣溪沙为什么不押韵呢？》一文明确写道'
