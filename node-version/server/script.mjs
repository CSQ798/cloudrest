// 繁体字检测
//
// 为什么要查：
//   模型偶尔会飘到繁体去。实测出现过「隔岸樓高燈自密 / 我衣露重影相仍」——
//   一首诗里繁简混用，是最刺眼的破绽，比平仄不合更伤读感。
//   站内全篇是简体，诗词正文也必须一律简体。
//
// 为什么不做「自动转换」：
//   机械转换看着更省事，但只要表里混进一个错字（把某个本来就在简体里
//   通用的字当成繁体），就会**无声地改坏一首好诗**。
//   所以这里只做判定：查出繁体字，交回给模型，让它自己重写。
//   判错的最坏后果是多花一次调用，不会污染成品。
//
// 表的写法：每项是「繁简」两字，空格分隔，按部首/类别分组，便于校对。
// 载入时自检：每项必须正好两个字，且两字必须不同——
// 手写打错（如把「楼楼」写进去）会立刻抛错，不会悄悄失效。
//
// 刻意不收的字（收了就会误伤简体正常用法）：
//   著（著作）、藉（慰藉）、乾（乾坤）、徵（宫商角徵羽）、祇（神祇）、
//   澹（澹泊）、面/里/台/只/并/后/发 等简体本身也在用的字。
//   ——凡是在简体里**也**是规范用法的字，一律不列。

