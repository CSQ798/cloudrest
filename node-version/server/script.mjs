/* ---------- 载入时自检：写错立刻抛错，不静默失效 ---------- */
const MAP = new Map();
{
  const items = GROUPS.join(' ').split(/\s+/).filter(Boolean);
  const bad = [];
  for (const it of items) {
    const chars = [...it];
    if (chars.length !== 2) bad.push(`「${it}」不是两个字`);
    else if (chars[0] === chars[1]) bad.push(`「${it}」繁简同字，多半是手误`);
    else MAP.set(chars[0], chars[1]);
  }
  if (bad.length) {
    throw new Error('server/script.mjs 的繁简表有 ' + bad.length + ' 处写错：\n  ' + bad.join('\n  '));
  }
}

export const TRAD_CHAR_COUNT = MAP.size;

/**
 * 查一行里的繁体字。
 * @param {string} line 一行正文（已由 hanzi() 提纯）
 * @returns {string[]} 形如 ['樓（应作「楼」）', ...]，无则空数组
 */
export function checkScript(line) {
  const out = [];
  for (const ch of String(line)) {
    const simp = MAP.get(ch);
    if (simp) out.push(`${ch}（应作「${simp}」）`);
  }
  return out;
}

