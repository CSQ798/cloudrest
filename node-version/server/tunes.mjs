// 为什么不能靠 rhymes 推：rhymes 说的是「哪里押韵」，而标点说的是「哪里是一句的结尾」。
// 《定风波》全篇十一个小句**处处押韵**，若按韵位标点，就变成每句后面一个句号 ——
// 那正是站长一眼挑出来的错。
