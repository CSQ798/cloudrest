/** 把句子按分片切开，返回 [[上片句], [下片句]] */
export function splitStanzas(tune) {
  const out = [];
  let i = 0;
  for (const n of tune.stanzas) {
    out.push(tune.lens.slice(i, i + n).map((len, k) => ({
      len,
      tones: tune.tones[i + k],
      rhyme: Boolean(tune.rhymes[i + k]),
    })));
    i += n;
  }
  return out;
}
