/** 取某个词牌的句读标点；没有（或与词谱句数对不上）就返回 null */export function getMarks(name) {
  const tune = TUNES.find((t) => t.name === name);
  const s = MARKS[name];
  if (!tune || typeof s !== 'string') return null;
  const chars = [...s];
  return chars.length === tune.lens.length ? chars : null;
}

export function getTune(name) {
  return TUNES.find((t) => t.name === name) || null;
}

